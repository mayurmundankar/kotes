// Builds supabase/seed.sql from src/data/quotes.json.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync } from "node:fs";

const quotes = JSON.parse(readFileSync(new URL("../src/data/quotes.json", import.meta.url), "utf8"));
const lit = (s) => (s == null ? "null" : `'${String(s).replaceAll("'", "''")}'`);
const arr = (xs) => `array[${xs.map(lit).join(", ")}]::text[]`;

const rows = quotes.map((q) => `  (${lit(q.text)}, ${lit(q.author)}, ${lit(q.source)}, ${arr(q.tags)})`);
const sql = `-- Generated by scripts/gen-seed.mjs — do not edit by hand.
insert into kotes.quotes (body, author, source, tags) values
${rows.join(",\n")}
on conflict (body) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${quotes.length} quotes`);
